const sourceStrings = [...source.matchAll(/^[ \t]*(?:name|title|description|label):[ \t]*(.*?)[ \t]*$/gm)]
  .map((match) => match[1])
  .filter(Boolean);
const uniqueStrings = [...new Set(sourceStrings)];
const missing = uniqueStrings.filter((text) => !translations.has(text));
if (missing.length) {
  throw new Error(`Missing ${missing.length} translations:\n${missing.join("\n")}`);
}

